#pragma once

#include <cstddef>
#include <optional>
#include <string>
#include <string_view>

namespace taskq {

// Проверки ввода, которые нашёл фаззер из домашнего задания этапа 3. Каждая
// закрыта тестом в tests/test_validate.cpp; что именно пропускал разбор до
// них, написано в tests/test_fuzz.cpp.
//
// Функции возвращают причину отказа, а не бросают: ими пользуются оба пути
// разбора — и на исключениях, и на Result, — и путь сам решает, как
// доставить ошибку.

// Строка длиннее этого предела отвергается целиком, до разбора. Тело задачи
// может быть большим законно, поэтому предел щедрее, чем у чата, но он есть:
// без него тело в мегабайты целиком ложилось в очередь, а на этапе 15 так
// можно было бы исчерпать память сервера одним клиентом.
inline constexpr std::size_t max_line_length = 64 * 1024;

// Имя очереди не длиннее 64 байт.
inline constexpr std::size_t max_queue_name_length = 64;

// Строгая проверка UTF-8: обрезанные последовательности, лишние байты
// продолжения, избыточные (overlong) формы и суррогаты — ошибка. Двоичные
// данные передаются через bin:, а не сырыми байтами.
[[nodiscard]] bool is_valid_utf8(std::string_view text) noexcept;

// Имя очереди: непустое, без пробелов по краям и управляющих символов, не
// длиннее 64 байт. Пробелы внутри разрешены — "build tasks" в кавычках.
[[nodiscard]] std::optional<std::string> queue_name_problem(std::string_view queue);

}  // namespace taskq
