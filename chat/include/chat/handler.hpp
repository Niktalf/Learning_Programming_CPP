// проверить тестом. Правило из docs/errors.md — внутри ядра ловить и
// проглатывать нельзя, только бросать — проверяется тем, что до handle
// исключения доходят целыми.
//
// На этапе 15 ровно эту функцию будет вызывать сетевая сессия, а на этапе 16 —
// обработчик HTTP-запроса. Ошибка одного клиента не должна ронять сервер.
